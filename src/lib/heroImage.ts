/**
 * Общие параметры адаптивного фото первого экрана (LCP-элемент).
 *
 * Используются в двух разных местах: в теге <Image> внутри Hero.astro и
 * в getImage() для preload-ссылки в <head>, которую строит index.astro.
 * Если бы widths/sizes продублировали как литералы в обоих местах, они
 * могли бы разойтись при правке одного без другого — тогда preload тянул
 * бы не тот файл, который браузер по тем же правилам выбора кандидата
 * реально подставляет в <img>, и предзагрузка работала бы против LCP,
 * а не на него.
 */
export const heroImageWidths = [395, 768, 1440, 2880];
/**
 * Порог здесь — lg (1024px), синхронно с Hero.astro: до lg макет
 * одноколоночный (фото на всю ширину под текстом, в том числе в диапазоне
 * 768-1023px — см. комментарий у heroLeftGutter в Hero.astro), а не 768px,
 * как почти везде в остальном макете. Разошлись бы — <img> получал бы
 * правильный по факту рендеринга размер, а sizes лгал бы браузеру, что
 * фото — половина экрана, когда оно на самом деле во всю ширину, и он бы
 * выбрал из srcset кандидата вдвое меньше нужного.
 *
 * От lg и выше фото — не ровно 50vw. Текстовая колонка держится
 * содержимым (h1 max-w-[567px]), а не процентом, поэтому у нижней границы
 * lg (1024px) фото занимает заметно меньше половины окна — около 35%, не
 * 50% — и растёт к 50vw только когда контейнер (1320px) перестаёт расти
 * вширь и вся дальнейшая ширина окна делится ровно пополам между текстом
 * и фото. Реальная геометрия (вывод из heroLeftGutter в Hero.astro,
 * сверено по факту рендера на 1024/1100/1200/1300/1320/1440/1920 —
 * см. таблицу замеров в отчёте задачи):
 *
 *   1024px ≤ окно ≤ 1320px:  ширина фото = 100vw - 667px
 *                             (40px отступ текста + 567px h1 + 60px gap)
 *   окно > 1320px:            ширина фото = 50vw - 7px
 *                             (после 1320px контейнер и текст, и фото
 *                             растут каждый на половину лишней ширины)
 *
 * Единственное число 50vw (без второго условия) на 1024px обещало 512px
 * вместо фактических 357px — почти вдвое больше — и браузер выбирал из
 * srcset кандидата 768w (12 КБ) вместо нужных 395w (4.8 КБ). Три условия
 * ниже — по одному на каждый из трёх геометрических режимов (одна
 * колонка / формула 100vw-667px / формула 50vw-7px), первое совпавшее по
 * media-условию побеждает, поэтому order важен: сначала самое широкое
 * условие (min-width: 1320px), потом (min-width: 1024px), иначе на
 * ширинах ≥1320px сработало бы правило для 1024px и снова обмануло
 * браузер.
 */
export const heroImageSizes =
  '(min-width: 1320px) calc(50vw - 7px), (min-width: 1024px) calc(100vw - 667px), 100vw';
