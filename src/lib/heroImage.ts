/**
 * Общие параметры адаптивного фото первого экрана (LCP-элемент).
 *
 * Используются в двух разных местах: в теге <Image> внутри Hero.astro и
 * в getImage() для preload-ссылки в <head>, которую строит index.astro.
 * Если бы widths/sizes продублировали как литералы в обоих местах, они
 * могли бы разойтись при правке одного без другого — тогда preload тянул
 * бы не тот файл, который браузер по тем же правилам выбора кандидата
 * реально подставляет в <img>, и предзагрузка работала бы против LCP,
 * а не на него.
 */
export const heroImageWidths = [395, 768, 1440, 2880];
/**
 * Секция первого экрана — на всю ширину окна (не внутри Container), фото
 * прижато к правому краю и занимает всё, что осталось от текстовой
 * колонки (её ширина держится контентом — h1 максимум 567px — а не
 * процентом). При таком делении фото на десктопе выходит около 48-50% от
 * ширины окна почти на любой ширине ≥1024px, отсюда 50vw ниже.
 *
 * Порог здесь — lg (1024px), синхронно с Hero.astro: до lg макет
 * одноколоночный (фото на всю ширину под текстом, в том числе в диапазоне
 * 768-1023px — см. комментарий у heroLeftGutter в Hero.astro), а не 768px,
 * как почти везде в остальном макете. Разошлись бы — <img> получал бы
 * правильный по факту рендеринга размер, а sizes лгал бы браузеру, что
 * фото — половина экрана, когда оно на самом деле во всю ширину, и он бы
 * выбрал из srcset кандидата вдвое меньше нужного.
 */
export const heroImageSizes = '(min-width: 1024px) 50vw, 100vw';
